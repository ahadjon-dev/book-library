def download_cover(isbn: str) -> bytes | None:
    if not isbn:
        return None
    url = f"https://covers.openlibrary.org/b/isbn/{isbn}-M.jpg"
    req = urllib.request.Request(url, headers={"User-Agent": "BookLibrary/1.0"})
    try:
        with urllib.request.urlopen(req, timeout=4) as resp:
            data = resp.read()
            if len(data) > 1000:
                return data
    except Exception:
        pass
    return None


def fetch_all_covers(books_list: list[dict]) -> dict[str, str | None]:
    covers_dir = Path(settings.uploads_dir) / "covers"
    covers_dir.mkdir(parents=True, exist_ok=True)
    results = {}

    print(f"Fetching covers for {len(books_list)} books from Open Library...")

    def process_book(book_info):
        isbn = book_info.get("isbn")
        if not isbn:
            return isbn, None
        data = download_cover(isbn)
        if data:
            filename = f"{uuid.uuid4().hex}.jpg"
            (covers_dir / filename).write_bytes(data)
            return isbn, f"covers/{filename}"
        return isbn, None

    with concurrent.futures.ThreadPoolExecutor(max_workers=16) as executor:
        futures = {executor.submit(process_book, b): b for b in books_list}
        count = 0
        for fut in concurrent.futures.as_completed(futures):
            isbn, path = fut.result()
            if isbn:
                results[isbn] = path
            count += 1
            if count % 25 == 0 or count == len(books_list):
                print(f"  Processed {count}/{len(books_list)} covers...")

    return results


def export_csv(books_list: list[dict], filepath: str) -> None:
    headers = [
        "title", "subtitle", "authors", "isbn", "publisher", "publication_year",
        "language", "page_count", "description", "genre", "tags", "shelf",
        "purchase_date", "purchase_price"
    ]
    with open(filepath, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=headers)
        writer.writeheader()
        for b in books_list:
            writer.writerow({
                "title": b["title"],
                "subtitle": b.get("subtitle") or "",
                "authors": ";".join(b["authors"]),
                "isbn": b.get("isbn") or "",
                "publisher": b.get("publisher") or "",
                "publication_year": b.get("publication_year") or "",
                "language": b.get("language") or "English",
                "page_count": b.get("page_count") or "",
                "description": b.get("description") or "",
                "genre": b.get("genre") or "General",
                "tags": ";".join(b.get("tags") or []),
                "shelf": b.get("shelf") or "Main",
                "purchase_date": b.get("purchase_date") or "2023-01-15",
                "purchase_price": b.get("purchase_price") or "15.00",
            })
    print(f"Exported {len(books_list)} books to CSV: {filepath}")


def populate_db(books_list: list[dict], cover_map: dict[str, str | None]) -> None:
    db = SessionLocal()
    try:
        users = db.query(User).all()
        admin_user = users[0] if users else None

        author_cache = {a.name: a for a in db.query(Author).all()}
        tag_cache = {t.name: t for t in db.query(Tag).all()}
        shelf_cache = {s.name: s for s in db.query(Shelf).all()}

        def get_or_create_author(name: str):
            if name not in author_cache:
                a = Author(name=name)
                db.add(a)
                db.flush()
                author_cache[name] = a
            return author_cache[name]

        def get_or_create_tag(name: str):
            if name not in tag_cache:
                t = Tag(name=name)
                db.add(t)
                db.flush()
                tag_cache[name] = t
            return tag_cache[name]

        def get_or_create_shelf(name: str):
            if name not in shelf_cache:
                s = Shelf(name=name)
                db.add(s)
                db.flush()
                shelf_cache[name] = s
            return shelf_cache[name]

        existing_books = {b.title.strip().lower() for b in db.query(Book).all()}
        inserted = 0

        for b in books_list:
            if b["title"].strip().lower() in existing_books:
                continue

            isbn = b.get("isbn")
            cover_path = cover_map.get(isbn)

            book = Book(
                title=b["title"],
                subtitle=b.get("subtitle"),
                isbn=isbn,
                publisher=b.get("publisher"),
                publication_year=b.get("publication_year"),
                language=b.get("language") or "English",
                page_count=b.get("page_count"),
                cover_image_path=cover_path,
                description=b.get("description"),
                genre=b.get("genre"),
                owned=b.get("owned", True),
                purchase_date=date(2022 + random.randint(0, 4), random.randint(1, 12), random.randint(1, 28)),
                purchase_price=Decimal(b.get("purchase_price", "15.00")),
            )
            db.add(book)
            book.authors = [get_or_create_author(a) for a in b["authors"]]
            book.tags = [get_or_create_tag(t) for t in b.get("tags", [])]
            if b.get("shelf"):
                book.shelf = get_or_create_shelf(b["shelf"])

            db.flush()

            if admin_user and book.owned:
                status_choice = random.choices(
                    [ReadStatus.finished, ReadStatus.reading, ReadStatus.unread, ReadStatus.abandoned],
                    weights=[0.55, 0.15, 0.25, 0.05],
                    k=1
                )[0]
                rating = random.randint(7, 10) if status_choice == ReadStatus.finished else (random.randint(5, 8) if status_choice == ReadStatus.abandoned else None)
                finish_date = date(2024 + random.randint(0, 2), random.randint(1, 12), random.randint(1, 28)) if status_choice == ReadStatus.finished else None
                start_date = (finish_date - timedelta(days=random.randint(5, 30))) if finish_date else (date(2026, 8, random.randint(1, 25)) if status_choice == ReadStatus.reading else None)

                user_status = UserBookStatus(
                    user_id=admin_user.id,
                    book_id=book.id,
                    status=status_choice,
                    rating=rating,
                    notes=f"Great read! Thoroughly enjoyed {book.title}." if rating and rating >= 9 else None,
                    started_at=start_date,
                    finished_at=finish_date,
                )
                db.add(user_status)

            inserted += 1
            existing_books.add(b["title"].strip().lower())

        db.commit()
        print(f"Successfully migrated {inserted} books into the database!")

    finally:
        db.close()


